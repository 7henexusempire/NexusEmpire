import fs from 'fs';
import path from 'path';
import { ChannelItem } from '../types';

const DATA_DIR = process.env.DATA_DIR || path.resolve(process.cwd(), 'data');
const REBUILD_FILE = path.join(DATA_DIR, 'rebuilt-playlists.json');

export interface RebuiltPlaylist {
  id: string;
  slug: string; // e.g. 'custom-sports' -> /api/rebuilt/custom-sports.m3u
  name: string;
  description: string;
  targetType: 'nexusempire' | 'normal';
  targetSourceOrCategory: string; // e.g. 'zee' or 'plugx' or 'all'
  customCategories: Record<string, string[]>; // categoryName -> channelIds
  namePrefix?: string;
  nameSuffix?: string;
  groupPrefix?: string;
  groupSuffix?: string;
  startChannelNumber?: number;
  enableChannelNumbering?: boolean;
  createdAt: string;
  updatedAt: string;
}

class RebuildService {
  private playlists: RebuiltPlaylist[] = [];

  constructor() {
    this.load();
  }

  private load() {
    try {
      if (fs.existsSync(REBUILD_FILE)) {
        const raw = fs.readFileSync(REBUILD_FILE, 'utf-8');
        const data = JSON.parse(raw);
        if (Array.isArray(data)) {
          this.playlists = data;
        }
      }
    } catch (err) {
      console.error('Failed to load rebuilt playlists:', err);
    }
  }

  private save() {
    try {
      if (!fs.existsSync(DATA_DIR)) {
        fs.mkdirSync(DATA_DIR, { recursive: true });
      }
      fs.writeFileSync(REBUILD_FILE, JSON.stringify(this.playlists, null, 2), 'utf-8');
    } catch (err) {
      console.error('Failed to save rebuilt playlists:', err);
    }
  }

  public getAll(): RebuiltPlaylist[] {
    return this.playlists;
  }

  public getById(idOrSlug: string): RebuiltPlaylist | undefined {
    return this.playlists.find((p) => p.id === idOrSlug || p.slug === idOrSlug);
  }

  public create(data: {
    name: string;
    description?: string;
    slug?: string;
    targetType: 'nexusempire' | 'normal';
    targetSourceOrCategory: string;
    customCategories?: Record<string, string[]>;
    namePrefix?: string;
    nameSuffix?: string;
    groupPrefix?: string;
    groupSuffix?: string;
    startChannelNumber?: number;
    enableChannelNumbering?: boolean;
  }): RebuiltPlaylist {
    const slug = (data.slug || data.name).toLowerCase().replace(/[^a-z0-9_-]/g, '-');
    const id = `rebuild_${Date.now()}`;
    const newPlaylist: RebuiltPlaylist = {
      id,
      slug,
      name: data.name,
      description: data.description || 'Custom rebuilt playlist from Nexus Studio',
      targetType: data.targetType,
      targetSourceOrCategory: data.targetSourceOrCategory,
      customCategories: data.customCategories || { 'Main Bouquet': [] },
      namePrefix: data.namePrefix || '',
      nameSuffix: data.nameSuffix || '',
      groupPrefix: data.groupPrefix || '',
      groupSuffix: data.groupSuffix || '',
      startChannelNumber: data.startChannelNumber || 1,
      enableChannelNumbering: data.enableChannelNumbering || false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    this.playlists.push(newPlaylist);
    this.save();
    return newPlaylist;
  }

  public update(id: string, updates: Partial<RebuiltPlaylist>): RebuiltPlaylist | null {
    const p = this.playlists.find((x) => x.id === id);
    if (!p) return null;

    if (updates.slug) {
      updates.slug = updates.slug.toLowerCase().replace(/[^a-z0-9_-]/g, '-');
    }

    Object.assign(p, updates, { updatedAt: new Date().toISOString() });
    this.save();
    return p;
  }

  public delete(id: string): boolean {
    const idx = this.playlists.findIndex((x) => x.id === id);
    if (idx !== -1) {
      this.playlists.splice(idx, 1);
      this.save();
      return true;
    }
    return false;
  }

  public generateM3U(slug: string, allChannels: ChannelItem[]): string {
    const p = this.getById(slug);
    if (!p) return '#EXTM3U\n# Playlist not found';

    const lines: string[] = [
      '#EXTM3U url-tvg="https://avkb.short.gy/jioepg.xml.gz" x-tvg-url="https://epgshare01.online/epgshare01/epg_ripper_IN4.xml.gz" refresh="1800"',
      `# Rebuilt Playlist: ${p.name} | Generated by Nexus Studio`,
      `# Description: ${p.description}`,
      `# Generated: ${new Date().toISOString()}`,
    ];

    const channelMap = new Map(allChannels.map((c) => [c.id, c]));
    let chnoCounter = typeof p.startChannelNumber === 'number' ? p.startChannelNumber : 1;

    for (const [catName, channelIds] of Object.entries(p.customCategories)) {
      const finalGroupName = `${p.groupPrefix || ''}${catName}${p.groupSuffix || ''}`;

      lines.push('');
      lines.push(`# ============================================================`);
      lines.push(`# Category: ${finalGroupName}`);
      lines.push(`# ============================================================`);

      for (const cId of channelIds) {
        const ch = channelMap.get(cId);
        if (!ch) continue;

        const rawName = ch.customName || ch.name;
        const displayName = `${p.namePrefix || ''}${rawName}${p.nameSuffix || ''}`;
        const logo = ch.customLogo || ch.tvgLogo || ch.logo || 'https://ik.imagekit.io/7henexusempire/nexusprime.png?updatedAt=1793203628547';
        const tvgId = ch.tvgId || ch.id;
        const streamUrl = ch.customUrl || ch.url;

        if (ch.preDirectives && ch.preDirectives.length > 0) {
          for (const d of ch.preDirectives) lines.push(d);
        }

        let extInfParts = [`#EXTINF:-1`];
        if (tvgId) extInfParts.push(`tvg-id="${tvgId}"`);
        extInfParts.push(`tvg-name="${displayName}"`);
        if (logo) extInfParts.push(`tvg-logo="${logo}"`);
        extInfParts.push(`group-title="${finalGroupName}"`);

        if (p.enableChannelNumbering) {
          extInfParts.push(`tvg-chno="${chnoCounter++}"`);
        } else if (ch.customChno || ch.tvgChno) {
          extInfParts.push(`tvg-chno="${ch.customChno || ch.tvgChno}"`);
        }

        lines.push(`${extInfParts.join(' ')},${displayName}`);

        if (ch.postDirectives && ch.postDirectives.length > 0) {
          for (const d of ch.postDirectives) lines.push(d);
        } else if (ch.directives && ch.directives.length > 0) {
          for (const d of ch.directives) lines.push(d);
        }

        lines.push(streamUrl);
      }
    }

    return lines.join('\n');
  }
}

export const rebuildService = new RebuildService();
